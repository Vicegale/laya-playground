// Sharing immutable parent lists must retain nested write isolation.
const original={profile:{nested:{name:'parent'}},rows:[{id:'001'}]};
const ctx={vars:{...original}};
setVar(ctx,'profile.nested.name','child');
assert.equal(original.profile.nested.name,'parent');
assert.equal(ctx.vars.profile.nested.name,'child');
assert.equal(ctx.vars.rows,original.rows,'Untouched large datasets are shared, not copied per row');
setVar(ctx,'__proto__.polluted','no');
assert.equal(Object.prototype.polluted,undefined);
const isolated={nodes:[n('set','set',{assignments:[{path:'profile.nested.name',value:'child'},{path:'profile.copiedName',value:'{{profile.nested.name}}'}]}),n('out','output',{value:'{{profile}}'})],edges:[e('set','next','out')]};
const parent={nodes:[n('map','map',{source:'{{input}}',resultAs:'mapped',mode:'workflow',workflow:isolated}),n('out','output',{value:'{{profile}}'})],edges:[e('map','done','out')]};
const isolatedResult=await executeWorkflow(parent,{input:[1,2],vars:structuredClone(original),decisions:{},locals:{}});
assert.equal(isolatedResult.output.nested.name,'parent');
assert.ok(isolatedResult.context.vars.mapped.every(row=>row.nested.name==='child'));
assert.ok(isolatedResult.context.vars.mapped.every(row=>row.copiedName==='child'),'Sequential writes resolve the current item scope');
